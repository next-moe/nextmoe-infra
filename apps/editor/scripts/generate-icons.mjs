#!/usr/bin/env node
// Writes app/assets/kun-icons.ts: every `lucide:<name>` literal used under app/
// resolved to its SVG body, fed to registerKunIcons() so <KunIcon> renders
// inline instead of fetching. Re-run with `pnpm --filter editor icons`.
import { readFile, readdir, writeFile } from 'node:fs/promises'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SCAN_DIR = join(ROOT, 'app')
const OUTPUT = join(ROOT, 'app/assets/kun-icons.ts')
const SCAN_EXT = /\.(vue|ts|tsx|js|mjs)$/
const SKIP = new Set(['node_modules', '.nuxt', '.output', 'dist'])
const ICON_PATTERN = /["']([a-z][a-z0-9-]{1,30}):([a-z0-9][a-z0-9-]{0,60})["']/g
const COLLECTIONS = new Set(['lucide'])

const listFiles = async (dir) => {
  const entries = await readdir(dir, { withFileTypes: true }).catch(() => [])
  const nested = await Promise.all(
    entries
      .filter((e) => !SKIP.has(e.name))
      .map((e) => {
        const full = join(dir, e.name)
        if (e.isDirectory()) return listFiles(full)
        return SCAN_EXT.test(e.name) && full !== OUTPUT ? [full] : []
      })
  )
  return nested.flat()
}

const loadCollection = (name) =>
  JSON.parse(
    readFileSync(require.resolve(`@iconify-json/${name}/icons.json`), 'utf8')
  )

// Renamed icons stay in the set as aliases (lucide:trash-2 → trash); reading
// only `icons` renders those blank.
const resolveIcon = (set, icon) => {
  let name = icon
  for (let hops = 0; !set.icons?.[name] && hops < 5; hops++) {
    const alias = set.aliases?.[name]
    if (!alias || Object.keys(alias).length > 1) return null
    name = alias.parent
  }
  return set.icons?.[name] ?? null
}

const main = async () => {
  const wanted = new Set()
  for (const file of await listFiles(SCAN_DIR)) {
    const content = await readFile(file, 'utf8')
    for (const [, collection, icon] of content.matchAll(ICON_PATTERN)) {
      if (COLLECTIONS.has(collection) && !/^\d+$/.test(icon)) {
        wanted.add(`${collection}:${icon}`)
      }
    }
  }
  const sets = new Map()
  const lines = []
  const missing = []
  for (const name of [...wanted].sort()) {
    const [collection, icon] = name.split(':')
    if (!sets.has(collection)) sets.set(collection, loadCollection(collection))
    const set = sets.get(collection)
    const def = resolveIcon(set, icon)
    if (!def || typeof def.body !== 'string') {
      missing.push(name)
      continue
    }
    const w = def.width ?? set.width
    const h = def.height ?? set.height
    const extra =
      (w && w !== 24 ? `, width: ${w}` : '') +
      (h && h !== 24 ? `, height: ${h}` : '')
    lines.push(
      `  ${JSON.stringify(name)}: { body: ${JSON.stringify(def.body)}${extra} }`
    )
  }
  await writeFile(
    OUTPUT,
    `// Generated by scripts/generate-icons.mjs — run \`pnpm --filter editor icons\`.
import type { KunIconData } from '@kungal/ui-core'

export const KUN_ICONS: Record<string, KunIconData> = {
${lines.join(',\n')}
}
`
  )
  console.log(`Wrote ${lines.length} icons → app/assets/kun-icons.ts`)
  if (missing.length) {
    console.warn(`Missing icons: ${missing.join(', ')}`)
    process.exitCode = 1
  }
}

main()
