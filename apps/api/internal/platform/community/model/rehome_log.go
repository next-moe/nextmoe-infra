package model

import (
	"time"

	"gorm.io/datatypes"
)

const (
	RehomeMoved   int16 = 1
	RehomeFolded  int16 = 2
	RehomeRetired int16 = 3
)

// CommunityRehomeLog is what retire-merged-comments did to one conversation on
// a merged-away work, kept so an undone catalog merge can put it back. State
// holds the thread as it was: its counters, post ids, read state,
// notification ids and the old anchor's subscriptions.
type CommunityRehomeLog struct {
	ID           int64          `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	Site         string         `gorm:"not null;index:idx_community_rehome_log_anchor,priority:1" json:"site"`
	AnchorKind   int16          `gorm:"not null;index:idx_community_rehome_log_anchor,priority:2" json:"anchor_kind"`
	OldAnchorID  string         `gorm:"not null;index:idx_community_rehome_log_anchor,priority:3" json:"old_anchor_id"`
	NewAnchorID  string         `gorm:"not null;default:''" json:"new_anchor_id"`
	CatalogOldID int64          `gorm:"not null" json:"catalog_old_id"`
	Action       int16          `gorm:"not null" json:"action"`
	ThreadID     int64          `gorm:"not null" json:"thread_id"`
	IntoThreadID *int64         `json:"into_thread_id"`
	PostOffset   int32          `gorm:"not null;default:0" json:"post_offset"`
	State        datatypes.JSON `gorm:"type:jsonb;not null" json:"state"`
	CreatedAt    time.Time      `gorm:"not null;default:now()" json:"created_at"`
	RevertedAt   *time.Time     `json:"reverted_at"`
}

func (CommunityRehomeLog) TableName() string { return "community_rehome_log" }
