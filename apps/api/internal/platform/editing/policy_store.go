package editing

import (
	"context"
	"encoding/json"
	"errors"
	"log/slog"
	"time"

	"gorm.io/datatypes"
	"gorm.io/gorm"
	"gorm.io/gorm/clause"
)

type PolicyOverrideRow struct {
	ID          int64     `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	EntityType  string    `gorm:"not null;uniqueIndex:uq_edit_policy_override,priority:1" json:"entity_type"`
	FieldKey    string    `gorm:"not null;default:'';uniqueIndex:uq_edit_policy_override,priority:2" json:"field_key"`
	Propose     *string   `json:"propose"`
	Review      *string   `json:"review"`
	Automerge   *string   `json:"automerge"`
	OwnerReview *bool     `json:"owner_review"`
	UpdatedBy   int64     `gorm:"not null" json:"updated_by"`
	UpdatedAt   time.Time `json:"updated_at"`
}

func (PolicyOverrideRow) TableName() string { return "edit_policy_override" }

func (r PolicyOverrideRow) override() PolicyOverride {
	return PolicyOverride{
		EntityType: r.EntityType, FieldKey: r.FieldKey,
		Propose: r.Propose, Review: r.Review, Automerge: r.Automerge, OwnerReview: r.OwnerReview,
	}
}

type PolicyOverrideAudit struct {
	ID         int64          `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	EntityType string         `gorm:"not null;index:idx_edit_policy_override_audit_target,priority:1" json:"entity_type"`
	FieldKey   string         `gorm:"not null;default:'';index:idx_edit_policy_override_audit_target,priority:2" json:"field_key"`
	Before     datatypes.JSON `gorm:"type:jsonb" json:"before"`
	After      datatypes.JSON `gorm:"type:jsonb" json:"after"`
	ActorUID   int64          `gorm:"column:actor_uid;not null" json:"actor_uid"`
	CreatedAt  time.Time      `json:"created_at"`
}

func (PolicyOverrideAudit) TableName() string { return "edit_policy_override_audit" }

var ErrOverrideNotFound = errors.New("editing: no policy override for that target")

const PolicyPollInterval = 30 * time.Second

type PolicyStore struct {
	db  *gorm.DB
	reg *Registry
}

func NewPolicyStore(db *gorm.DB, reg *Registry) *PolicyStore {
	return &PolicyStore{db: db, reg: reg}
}

func (s *PolicyStore) Registry() *Registry { return s.reg }

func (s *PolicyStore) Reload(ctx context.Context) error {
	var rows []PolicyOverrideRow
	if err := s.db.WithContext(ctx).Order("id").Find(&rows).Error; err != nil {
		return err
	}
	overrides := make([]PolicyOverride, 0, len(rows))
	for _, r := range rows {
		overrides = append(overrides, r.override())
	}
	for _, err := range s.reg.SetPolicyOverrides(overrides) {
		slog.Warn("editing: policy override skipped", "err", err)
	}
	return nil
}

func (s *PolicyStore) Start(ctx context.Context) {
	if err := s.Reload(ctx); err != nil {
		slog.Error("editing: initial policy override load failed; code defaults apply until the next poll", "err", err)
	}
	go func() {
		t := time.NewTicker(PolicyPollInterval)
		defer t.Stop()
		for {
			select {
			case <-ctx.Done():
				return
			case <-t.C:
				if err := s.Reload(ctx); err != nil {
					slog.Warn("editing: policy override poll failed; keeping the last table", "err", err)
				}
			}
		}
	}()
}

func (s *PolicyStore) Put(ctx context.Context, actorUID int64, o PolicyOverride) (PolicyOverrideRow, error) {
	if err := s.reg.ValidateOverride(o); err != nil {
		return PolicyOverrideRow{}, &ValidationError{Key: o.EntityType + "/" + o.FieldKey, Reason: err.Error()}
	}
	row := PolicyOverrideRow{
		EntityType: o.EntityType, FieldKey: o.FieldKey,
		Propose: o.Propose, Review: o.Review, Automerge: o.Automerge, OwnerReview: o.OwnerReview,
		UpdatedBy: actorUID, UpdatedAt: time.Now().UTC(),
	}
	err := s.db.WithContext(ctx).Transaction(func(tx *gorm.DB) error {
		before, err := lockOverride(tx, o.EntityType, o.FieldKey)
		if err != nil {
			return err
		}
		if err := tx.Clauses(clause.OnConflict{
			Columns:   []clause.Column{{Name: "entity_type"}, {Name: "field_key"}},
			DoUpdates: clause.AssignmentColumns([]string{"propose", "review", "automerge", "owner_review", "updated_by", "updated_at"}),
		}).Create(&row).Error; err != nil {
			return err
		}
		if err := tx.Where("entity_type = ? AND field_key = ?", o.EntityType, o.FieldKey).First(&row).Error; err != nil {
			return err
		}
		return writeAudit(tx, o.EntityType, o.FieldKey, before, &o, actorUID)
	})
	if err != nil {
		return PolicyOverrideRow{}, err
	}
	return row, s.Reload(ctx)
}

func (s *PolicyStore) Delete(ctx context.Context, actorUID int64, entityType, fieldKey string) error {
	err := s.db.WithContext(ctx).Transaction(func(tx *gorm.DB) error {
		before, err := lockOverride(tx, entityType, fieldKey)
		if err != nil {
			return err
		}
		if before == nil {
			return ErrOverrideNotFound
		}
		if err := tx.Where("entity_type = ? AND field_key = ?", entityType, fieldKey).
			Delete(&PolicyOverrideRow{}).Error; err != nil {
			return err
		}
		return writeAudit(tx, entityType, fieldKey, before, nil, actorUID)
	})
	if err != nil {
		return err
	}
	return s.Reload(ctx)
}

func (s *PolicyStore) Audit(ctx context.Context, limit int, beforeID int64) ([]PolicyOverrideAudit, error) {
	if limit <= 0 || limit > 200 {
		limit = 50
	}
	q := s.db.WithContext(ctx).Order("id DESC").Limit(limit)
	if beforeID > 0 {
		q = q.Where("id < ?", beforeID)
	}
	var out []PolicyOverrideAudit
	return out, q.Find(&out).Error
}

func lockOverride(tx *gorm.DB, entityType, fieldKey string) (*PolicyOverride, error) {
	var row PolicyOverrideRow
	err := tx.Clauses(clause.Locking{Strength: "UPDATE"}).
		Where("entity_type = ? AND field_key = ?", entityType, fieldKey).First(&row).Error
	if errors.Is(err, gorm.ErrRecordNotFound) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	o := row.override()
	return &o, nil
}

func writeAudit(tx *gorm.DB, entityType, fieldKey string, before, after *PolicyOverride, actorUID int64) error {
	entry := PolicyOverrideAudit{EntityType: entityType, FieldKey: fieldKey, ActorUID: actorUID}
	var err error
	if entry.Before, err = auditJSON(before); err != nil {
		return err
	}
	if entry.After, err = auditJSON(after); err != nil {
		return err
	}
	return tx.Create(&entry).Error
}

func DecodePolicyOverride(raw []byte) (PolicyOverride, error) {
	var o PolicyOverride
	err := json.Unmarshal(raw, &o)
	return o, err
}

func auditJSON(o *PolicyOverride) (datatypes.JSON, error) {
	if o == nil {
		return nil, nil
	}
	b, err := json.Marshal(o)
	return datatypes.JSON(b), err
}
