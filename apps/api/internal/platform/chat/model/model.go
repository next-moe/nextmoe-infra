type ChatUser struct {
	UserID            int64     `gorm:"primaryKey;autoIncrement:false;column:user_id" json:"user_id"`
	LastUpdateSeq     int64     `gorm:"not null;column:last_update_seq" json:"last_update_seq"`
	AllowIncoming     string    `gorm:"not null;check:chk_chat_user_allow_incoming,allow_incoming IN ('all','following','none');column:allow_incoming" json:"allow_incoming"`
	AcceptRequests    bool      `gorm:"not null;column:accept_requests" json:"accept_requests"`
	AllowGroupInvites string    `gorm:"not null;check:chk_chat_user_allow_group_invites,allow_group_invites IN ('all','following','none');column:allow_group_invites" json:"allow_group_invites"`
	CreatedAt         time.Time `gorm:"not null;column:created_at" json:"created_at"`
	UpdatedAt         time.Time `gorm:"not null;column:updated_at" json:"updated_at"`
}

func (ChatUser) TableName() string { return "chat_user" }

type ChatConversation struct {
	ID               int64      `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	Kind             string     `gorm:"not null;check:chk_chat_conversation_kind,kind IN ('direct','group');column:kind" json:"kind"`
	DirectUserLowID  *int64     `gorm:"check:chk_chat_conversation_direct_users,(kind = 'direct') = (direct_user_low_id IS NOT NULL AND direct_user_high_id IS NOT NULL);column:direct_user_low_id" json:"direct_user_low_id"`
	DirectUserHighID *int64     `gorm:"check:chk_chat_conversation_direct_order,direct_user_low_id <= direct_user_high_id;column:direct_user_high_id" json:"direct_user_high_id"`
	Title            *string    `gorm:"column:title" json:"title"`
	About            *string    `gorm:"column:about" json:"about"`
	PhotoImageHash   *string    `gorm:"column:photo_image_hash" json:"photo_image_hash"`
	CreatorID        int64      `gorm:"not null;column:creator_id" json:"creator_id"`
	OriginSite       string     `gorm:"not null;column:origin_site" json:"origin_site"`
	LastSeq          int64      `gorm:"not null;column:last_seq" json:"last_seq"`
	MemberCount      int32      `gorm:"not null;column:member_count" json:"member_count"`
	CreatedAt        time.Time  `gorm:"not null;column:created_at" json:"created_at"`
	UpdatedAt        time.Time  `gorm:"not null;column:updated_at" json:"updated_at"`
	DeletedAt        *time.Time `gorm:"column:deleted_at" json:"deleted_at"`
}

func (ChatConversation) TableName() string { return "chat_conversation" }

