type ChatMessage struct {
	ID              int64          `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	ConversationID  int64          `gorm:"not null;uniqueIndex:uq_chat_message_seq,priority:1;column:conversation_id" json:"conversation_id"`
	Seq             int64          `gorm:"not null;uniqueIndex:uq_chat_message_seq,priority:2;column:seq" json:"seq"`
	SenderID        int64          `gorm:"not null;uniqueIndex:uq_chat_message_client,priority:1;index:idx_chat_message_sender;column:sender_id" json:"sender_id"`
	Kind            string         `gorm:"not null;check:chk_chat_message_kind,kind IN ('message','service');column:kind" json:"kind"`
	Text            string         `gorm:"not null;column:text" json:"text"`
	Entities        datatypes.JSON `gorm:"type:jsonb;column:entities" json:"entities"`
	Media           datatypes.JSON `gorm:"type:jsonb;column:media" json:"media"`
	MediaGroupID    *int64         `gorm:"column:media_group_id" json:"media_group_id"`
	ReplyToSeq      *int64         `gorm:"column:reply_to_seq" json:"reply_to_seq"`
	ReplyQuote      datatypes.JSON `gorm:"type:jsonb;column:reply_quote" json:"reply_quote"`
	ForwardOrigin   datatypes.JSON `gorm:"type:jsonb;column:forward_origin" json:"forward_origin"`
	ServiceAction   datatypes.JSON `gorm:"type:jsonb;check:chk_chat_message_service,(kind = 'service') = (service_action IS NOT NULL);column:service_action" json:"service_action"`
	Context         datatypes.JSON `gorm:"type:jsonb;column:context" json:"context"`
	ClientMessageID *string        `gorm:"type:uuid;uniqueIndex:uq_chat_message_client,priority:2;column:client_message_id" json:"client_message_id"`
	OriginSite      string         `gorm:"not null;column:origin_site" json:"origin_site"`
	Silent          bool           `gorm:"not null;column:silent" json:"silent"`
	PinnedAt        *time.Time     `gorm:"column:pinned_at" json:"pinned_at"`
	EditedAt        *time.Time     `gorm:"column:edited_at" json:"edited_at"`
	DeletedAt       *time.Time     `gorm:"check:chk_chat_message_deleted_empty,deleted_at IS NULL OR (text = '' AND entities IS NULL AND media IS NULL AND reply_quote IS NULL AND context IS NULL);column:deleted_at" json:"deleted_at"`
	CreatedAt       time.Time      `gorm:"not null;column:created_at" json:"created_at"`

	Conversation *ChatConversation `gorm:"foreignKey:ConversationID;constraint:OnDelete:CASCADE" json:"-"`
}

func (ChatMessage) TableName() string { return "chat_message" }

