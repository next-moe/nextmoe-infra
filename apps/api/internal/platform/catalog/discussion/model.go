package discussion

import (
	"time"

	"gorm.io/datatypes"
	"gorm.io/gorm"
)

const (
	StatusVisible int16 = 0
	StatusHidden  int16 = 1
	StatusDeleted int16 = 2
)

type Post struct {
	ID             int64          `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-);index:idx_edit_discussion_post_anchor,priority:3"`
	AnchorKind     string         `gorm:"not null;index:idx_edit_discussion_post_anchor,priority:1"`
	AnchorID       int64          `gorm:"not null;index:idx_edit_discussion_post_anchor,priority:2"`
	AuthorUID      int64          `gorm:"column:author_uid;not null;index:idx_edit_discussion_post_author,priority:1"`
	Body           string         `gorm:"not null"`
	ReplyToID      *int64         `gorm:"column:reply_to_id"`
	MentionUIDs    datatypes.JSON `gorm:"column:mention_uids;type:jsonb;not null;default:'[]'"`
	AuthorReviewer bool           `gorm:"column:author_reviewer;not null;default:false"`
	Status         int16          `gorm:"not null;default:0"`
	ModeratedByUID *int64         `gorm:"column:moderated_by_uid"`
	ModeratedAt    *time.Time
	ModerationNote string `gorm:"not null;default:''"`
	EditedAt       *time.Time
	CreatedAt      time.Time `gorm:"index:idx_edit_discussion_post_author,priority:2"`
	UpdatedAt      time.Time
}

func (Post) TableName() string { return "edit_discussion_post" }

type Watcher struct {
	AnchorKind string `gorm:"primaryKey"`
	AnchorID   int64  `gorm:"primaryKey;autoIncrement:false"`
	UserID     int64  `gorm:"primaryKey;autoIncrement:false;index:idx_edit_discussion_watcher_user"`
	Muted      bool   `gorm:"not null;default:false"`
	CreatedAt  time.Time
	UpdatedAt  time.Time
}

func (Watcher) TableName() string { return "edit_discussion_watcher" }

func AutoMigrate(db *gorm.DB) error {
	return db.AutoMigrate(&Post{}, &Watcher{})
}
