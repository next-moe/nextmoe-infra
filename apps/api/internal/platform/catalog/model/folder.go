package model

import "time"

const (
	FolderVisibilityPrivate  int16 = 0
	FolderVisibilityPublic   int16 = 1
	FolderVisibilityUnlisted int16 = 2
)

func FolderVisibilityValid(v int16) bool {
	return v == FolderVisibilityPrivate || v == FolderVisibilityPublic || v == FolderVisibilityUnlisted
}

// Readable by anyone who has the id: public folders, and unlisted ones that
// stay out of every listing but open from a shared link.
func FolderReadable(v int16) bool {
	return v == FolderVisibilityPublic || v == FolderVisibilityUnlisted
}

