type CatalogUserFolder struct {
	ID            int64     `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	OwnerUID      int64     `gorm:"column:owner_uid;not null;index" json:"owner_uid"`
	Name          string    `gorm:"not null;size:100" json:"name"`
	Description   string    `gorm:"size:500" json:"description"`
	Visibility    int16     `gorm:"not null;default:0" json:"visibility"`
	IsDefault     bool      `gorm:"not null;default:false" json:"is_default"`
	ItemCount     int       `gorm:"not null;default:0" json:"item_count"`
	FollowerCount int       `gorm:"not null;default:0" json:"follower_count"`
	CreatedAt     time.Time `json:"created_at"`
	UpdatedAt     time.Time `json:"updated_at"`
}

func (CatalogUserFolder) TableName() string { return "catalog_user_folder" }

