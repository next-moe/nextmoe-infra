package model

import "time"

const DeletionStatusRestored int16 = 5

const (
	DeletionReasonNotAWork   = "not_a_work"
	DeletionReasonOutOfScope = "out_of_scope"
	DeletionReasonSpamOrTest = "spam_or_test"
	DeletionReasonOther      = "other"
)

var DeletionReasons = []string{
	DeletionReasonNotAWork, DeletionReasonOutOfScope, DeletionReasonSpamOrTest, DeletionReasonOther,
}

type CatalogDeletionRequest struct {
	ID           int64      `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	EntityType   int16      `gorm:"not null;index:idx_catalog_deletion_request_entity,priority:1" json:"entity_type"`
	EntityID     int64      `gorm:"not null;index:idx_catalog_deletion_request_entity,priority:2" json:"entity_id"`
	Reason       string     `gorm:"not null" json:"reason"`
	Note         string     `gorm:"not null;default:''" json:"note"`
	Status       int16      `gorm:"not null;index:idx_catalog_deletion_request_queue,priority:1" json:"status"`
	ProposedBy   int64      `gorm:"not null;index:idx_catalog_deletion_request_proposer,priority:1" json:"proposed_by"`
	ProposedAt   time.Time  `gorm:"not null;autoCreateTime;index:idx_catalog_deletion_request_proposer,priority:2" json:"proposed_at"`
	DecidedBy    *int64     `json:"decided_by"`
	DecidedAt    *time.Time `json:"decided_at"`
	DecisionNote string     `gorm:"not null;default:''" json:"decision_note"`
	ExecuteAfter *time.Time `json:"execute_after"`
	ExecutedAt   *time.Time `json:"executed_at"`
	ExecutedBy   *int64     `json:"executed_by"`
	PriorStatus  *int16     `json:"prior_status"`
	RestoredAt   *time.Time `json:"restored_at"`
	RestoredBy   *int64     `json:"restored_by"`
	RestoreNote  string     `gorm:"not null;default:''" json:"restore_note"`
	OriginSite   *string    `json:"origin_site"`
}

func (CatalogDeletionRequest) TableName() string { return "catalog_deletion_request" }
