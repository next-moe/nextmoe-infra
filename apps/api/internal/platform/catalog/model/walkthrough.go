package model

import (
	"time"

	"gorm.io/datatypes"
)

const (
	WalkthroughStatusLive   int16 = 0
	WalkthroughStatusHidden int16 = 1
)

const (
	WalkthroughLangJa     = "ja"
	WalkthroughLangZhHans = "zh-Hans"
)

const WalkthroughMatchedByCurated = "curated"

// A walkthrough written in the editor has no page to link to; its source_url
// holds this prefix and a uuid only to keep (source_id, source_url) unique.
const WalkthroughNativeURLPrefix = "editor:"

type CatalogWalkthrough struct {
	ID              int64          `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	WorkID          int64          `gorm:"not null;index" json:"work_id"`
	SourceID        int16          `gorm:"not null;uniqueIndex:uq_catalog_walkthrough_source" json:"source_id"`
	SourceURL       string         `gorm:"not null;uniqueIndex:uq_catalog_walkthrough_source" json:"source_url"`
	SourceAuthor    string         `gorm:"not null;default:''" json:"source_author"`
	SourceUpdatedOn *time.Time     `gorm:"type:date" json:"source_updated_on"`
	Status          int16          `gorm:"not null;default:0" json:"status"`
	ChartVersion    int16          `gorm:"not null" json:"chart_version"`
	Chart           datatypes.JSON `gorm:"type:jsonb;not null" json:"chart"`
	SourceHash      string         `gorm:"not null" json:"source_hash"`
	ExtractModel    string         `gorm:"not null" json:"extract_model"`
	TranslateModel  string         `gorm:"not null;default:''" json:"translate_model"`
	Lang            string         `gorm:"not null;default:'ja'" json:"lang"`
	FieldProvenance datatypes.JSON `gorm:"type:jsonb;not null;default:'{}'" json:"field_provenance"`
	CreatedAt       time.Time      `json:"created_at"`
	UpdatedAt       time.Time      `json:"updated_at"`
}

func (CatalogWalkthrough) TableName() string { return "catalog_walkthrough" }

type CatalogWalkthroughCharacter struct {
	WalkthroughID int64     `gorm:"primaryKey;autoIncrement:false" json:"walkthrough_id"`
	ChartKey      string    `gorm:"primaryKey" json:"chart_key"`
	CharacterID   int64     `gorm:"not null;index" json:"character_id"`
	MatchedBy     string    `gorm:"not null" json:"matched_by"`
	CreatedAt     time.Time `json:"created_at"`
}

func (CatalogWalkthroughCharacter) TableName() string { return "catalog_walkthrough_character" }
