package model

import (
	"time"

	"gorm.io/datatypes"
)

type SplitTitle struct {
	Lang  string `json:"lang"`
	Title string `json:"title"`
	Kind  int16  `json:"kind"`
}

type SplitRef struct {
	Source     string `json:"source"`
	ExternalID string `json:"external_id"`
}

type CatalogSplitRequest struct {
	ID           int64          `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	EntityType   int16          `gorm:"not null;index:idx_catalog_split_request_entity,priority:1" json:"entity_type"`
	EntityID     int64          `gorm:"not null;index:idx_catalog_split_request_entity,priority:2" json:"entity_id"`
	ReleaseIDs   datatypes.JSON `gorm:"type:jsonb;not null;default:'[]'" json:"release_ids"`
	DisplayName  string         `gorm:"not null" json:"display_name"`
	OLang        string         `gorm:"column:olang;not null" json:"olang"`
	Titles       datatypes.JSON `gorm:"type:jsonb;not null;default:'[]'" json:"titles"`
	PromoteRefs  datatypes.JSON `gorm:"type:jsonb;not null;default:'[]'" json:"promote_refs"`
	Note         string         `gorm:"not null;default:''" json:"note"`
	Status       int16          `gorm:"not null;index:idx_catalog_split_request_queue,priority:1" json:"status"`
	ProposedBy   int64          `gorm:"not null;index:idx_catalog_split_request_proposer,priority:1" json:"proposed_by"`
	ProposedAt   time.Time      `gorm:"not null;autoCreateTime;index:idx_catalog_split_request_proposer,priority:2" json:"proposed_at"`
	AmendedBy    *int64         `json:"amended_by"`
	AmendedAt    *time.Time     `json:"amended_at"`
	DecidedBy    *int64         `json:"decided_by"`
	DecidedAt    *time.Time     `json:"decided_at"`
	DecisionNote string         `gorm:"not null;default:''" json:"decision_note"`
	ExecuteAfter *time.Time     `json:"execute_after"`
	ExecutedAt   *time.Time     `json:"executed_at"`
	ExecutedBy   *int64         `json:"executed_by"`
	NewWorkID    *int64         `json:"new_work_id"`
	Execution    datatypes.JSON `gorm:"type:jsonb;not null;default:'{}'" json:"execution"`
	UndoneBy     *int64         `json:"undone_by"`
	UndoneAt     *time.Time     `json:"undone_at"`
	UndoNote     string         `gorm:"not null;default:''" json:"undo_note"`
	UndoMergeID  *int64         `json:"undo_merge_id"`
	ChangedAt    *time.Time     `gorm:"index:idx_catalog_split_request_changed" json:"changed_at"`
	OriginSite   *string        `gorm:"column:origin_site;size:16" json:"origin_site"`
}

func (CatalogSplitRequest) TableName() string { return "catalog_split_request" }
