package idseq

import (
	"context"
	"database/sql"
	"testing"
	"time"

	"api/internal/testsupport/dbtest"

	_ "github.com/jackc/pgx/v5/stdlib"
)

func TestAdoptionWaitsOutAnImportWithoutBlockingItsTable(t *testing.T) {
	dsn, ok := dbtest.DSN()
	if !ok {
		dbtest.Skip(t)
	}
	ctx := context.Background()
	db, err := sql.Open("pgx", dsn)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	lockWait, lockPause = 150*time.Millisecond, 150*time.Millisecond
	t.Cleanup(func() { lockWait, lockPause = 2*time.Second, 3*time.Second })
	drop := `DROP TABLE IF EXISTS public.idseq_probe; DROP SEQUENCE IF EXISTS canon_ids.probe`
	t.Cleanup(func() { _, _ = db.Exec(drop) })
	for _, q := range []string{`CREATE SCHEMA IF NOT EXISTS canon_ids`, drop,
		`CREATE TABLE public.idseq_probe (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v int)`,
		`INSERT INTO public.idseq_probe (v) VALUES (1), (2)`} {
		if _, err := db.Exec(q); err != nil {
			t.Fatal(err)
		}
	}
	hold := func() *sql.Tx {
		tx, err := db.Begin()
		if err != nil {
			t.Fatal(err)
		}
		if _, err := tx.Exec(`UPDATE public.idseq_probe SET v = v WHERE id = 1`); err != nil {
			t.Fatal(err)
		}
		return tx
	}
	family := Family{"idseq_probe", "probe"}
	importing := hold()
	result := make(chan error, 1)
	go func() { result <- adoptWithin(ctx, db, family) }()
	var slowest time.Duration
	for until := time.Now().Add(1200 * time.Millisecond); time.Now().Before(until); time.Sleep(20 * time.Millisecond) {
		started := time.Now()
		if _, err := db.Exec(`UPDATE public.idseq_probe SET v = v + 1 WHERE id = 2`); err != nil {
			t.Fatal(err)
		}
		slowest = max(slowest, time.Since(started))
	}
	if slowest > 400*time.Millisecond {
		t.Errorf("a writer waited %v behind the adoption", slowest)
	}
	_ = importing.Rollback()
	if err := <-result; err != nil {
		t.Fatalf("adopt once the import ended: %v", err)
	}
	var next int64
	if err := db.QueryRow(`INSERT INTO public.idseq_probe (v) VALUES (3) RETURNING id`).Scan(&next); err != nil || next != 3 {
		t.Errorf("the next id is %d, %v", next, err)
	}

	importing = hold()
	defer importing.Rollback()
	started := time.Now()
	if err := adoptWithin(ctx, db, family); err != nil || time.Since(started) > 100*time.Millisecond {
		t.Errorf("a second run takes no lock: %v in %v", err, time.Since(started))
	}
}
